const PENSION_MANAGER = 'Nyasha Banda'

function addDays(iso: string, days: number): string {
  const date = new Date(`${iso}T00:00:00`)
  date.setDate(date.getDate() + days)
  return date.toISOString().slice(0, 10)
}

function buildHistory(
  reference: string,
  status: NominationStatus,
  principalOfficer: string,
  submitted: string,
  rejectedBy = principalOfficer,
): ApprovalEvent[] {
  const history: ApprovalEvent[] = [
    {
      id: `${reference}-H1`,
      stage: 'Submission',
      actor: 'Employee self-service',
      decision: 'Submitted',
      date: submitted,
      comments: 'Nomination form submitted for review.',
    },
  ]

  if (status === 'Pending PO Approval') return history

  if (status === 'Rejected') {
    history.push({
      id: `${reference}-H2`,
      stage:
        rejectedBy === PENSION_MANAGER
          ? 'Pension Manager review'
          : 'Principal Officer review',
      actor: rejectedBy,
      decision: 'Rejected',
      date: addDays(submitted, 1),
      comments:
        'Supporting documents are incomplete. Please resubmit with a valid national ID copy.',
    })
    return history
  }

  history.push({
    id: `${reference}-H2`,
    stage: 'Principal Officer review',
    actor: principalOfficer,
    decision: 'Endorsed',
    date: addDays(submitted, 1),
    comments:
      'Member and beneficiary details verified. Endorsed for final approval.',
  })

  if (status === 'Pending PM Approval') return history

  history.push({
    id: `${reference}-H3`,
    stage: 'Pension Manager review',
    actor: PENSION_MANAGER,
    decision: 'Approved',
    date: addDays(submitted, 2),
    comments: 'Final approval granted. Beneficiary register updated.',
  })

  return history
}

